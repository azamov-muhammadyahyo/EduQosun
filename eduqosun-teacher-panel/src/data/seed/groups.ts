/** Demo guruh "chizmasi": sanalar bugungi kunga nisbatan beriladi */
export interface GroupBlueprint extends Omit<Group, 'createdAt' | 'startDate' | 'endDate'> {
  /** Kurs boshlanishi (bugundan necha kun oldin) */
  startDaysAgo: number
  /** Kurs davomiyligi (kun) */
  durationDays: number
  /** O'quvchilar tarkibi */
  roster: { active: number; left: number; transferred: number }
}

function slots(days: Weekday[], start: TimeString, end: TimeString, kinds: LessonKind[]): ScheduleSlot[] {
  return days.map((day, index) => ({ day, start, end, kind: kinds[index % kinds.length] }))
}

