/** Chizmadan haqiqiy guruh obyektini yasaydi */
export function buildGroup(blueprint: GroupBlueprint, today: DateKey): Group {
  const { startDaysAgo, durationDays, roster, ...rest } = blueprint
  void roster // tarkib faqat o'quvchilarni yaratishda kerak
  const startDate = addDays(today, -startDaysAgo)
  return {
    ...rest,
    startDate,
    endDate: addDays(startDate, durationDays),
    createdAt: isoAt(addDays(startDate, -3), '10:00'),
  }
}
